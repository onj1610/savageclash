import { execFileSync } from 'node:child_process'
import { randomUUID } from 'node:crypto'
import { existsSync, lstatSync, mkdirSync, readFileSync, realpathSync, renameSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { threejsAssetEntries, verifyThreejsAsset } from './threejs-asset-restore.mjs'

export class ThreejsAssetPreparationError extends Error {}

const marker = '// Generated by Manus asset storage.\n'
const directory = 'scripts/manus-game-assets'
const restoreCommand = `node ${directory}/restore.mjs`
export const THREEJS_ASSET_RESTORE_PREFIX = restoreCommand + ' && '
const sources = ['threejs-asset-inputs.mjs', 'threejs-asset-restore.mjs', 'asset-restore-policy.mjs', 'local-artifacts.mjs', 'asset-upload-journal.mjs', 'storage.mjs', 'install-asset.mjs']

function regularPath(root, relative) {
  const parts = relative.split('/')
  let target = root
  for (let i = 0; i < parts.length; i++) {
    target = join(target, parts[i])
    let stat
    try { stat = lstatSync(target) } catch (error) { if (error.code === 'ENOENT') continue; throw error }
    if (stat.isSymbolicLink() || (i === parts.length - 1 ? !stat.isFile() : !stat.isDirectory())) throw new ThreejsAssetPreparationError('Asset preparation requires regular project paths')
  }
  return target
}

function replaceFile(file, content) {
  const temporary = file + '.' + randomUUID() + '.tmp'
  mkdirSync(dirname(file), { recursive: true })
  try { writeFileSync(temporary, content, { flag: 'wx' }); renameSync(temporary, file) }
  finally { rmSync(temporary, { force: true }) }
}

/** Install recovery before excluding verified assets; existing commits and working files stay intact. */
export async function prepareThreejsAssets(root, { gitEnv = process.env, updateIndex = true } = {}) {
  root = realpathSync(root)
  // Local First owns a separate index; only the authorized Manus Git command selects it.
  if (existsSync(join(root, 'manus-webdev.json')) && !gitEnv.GIT_DIR) throw new ThreejsAssetPreparationError('Run asset synchronization through webdev.manus_git for this local project')
  const entries = threejsAssetEntries(root)
  if (!entries.length) return
  const pkgPath = regularPath(root, 'package.json')
  const pkg = JSON.parse(readFileSync(pkgPath, 'utf8'))
  if (!(pkg.dependencies?.three || pkg.devDependencies?.three) || typeof pkg.scripts?.build !== 'string' || !pkg.scripts.build.trim()) throw new ThreejsAssetPreparationError('Three.js asset storage requires a package.json build script')
  for (const script of ['build', 'dev']) {
    // A trailing pipeline or recovery clause could swallow a failed restoration.
    // Leave such custom commands intact instead of silently weakening their checks.
    if (typeof pkg.scripts[script] === 'string' && /[|;\r\n]|(?<!&)&(?!&)/u.test(pkg.scripts[script])) throw new ThreejsAssetPreparationError('Asset recovery requires build/dev commands joined with &&; move custom pipelines or recovery clauses into a project script before synchronization')
  }
  const ignorePath = regularPath(root, '.gitignore')
  const ignore = existsSync(ignorePath) ? readFileSync(ignorePath, 'utf8') : ''
  const files = sources.map(name => [regularPath(root, `${directory}/${name}`), marker + readFileSync(new URL(name, import.meta.url), 'utf8')])
  files.push([regularPath(root, `${directory}/restore.mjs`), marker + `import { restoreThreejsAssets, assetRestoreDiagnostic } from './threejs-asset-restore.mjs'
import { referencedLocalAssets } from './threejs-asset-inputs.mjs'
try {
  const root = process.cwd(), inputs = await referencedLocalAssets(root)
  await restoreThreejsAssets(root, { includeAsset: rel => inputs.has(rel) })
}
catch (error) { console.error(JSON.stringify(assetRestoreDiagnostic(error))); process.exitCode = 1 }
`])
  for (const [file] of files) {
    if (existsSync(file) && !readFileSync(file, 'utf8').startsWith(marker)) throw new ThreejsAssetPreparationError('Asset preparation would overwrite a custom script')
  }
  for (const [rel, entry] of entries) await verifyThreejsAsset(join(root, rel), entry)
  const git = (args, options = {}) => execFileSync('git', args, { cwd: root, env: gitEnv, stdio: 'pipe', timeout: 60_000, ...options })
  let gitRoot
  try { gitRoot = realpathSync(git(['rev-parse', '--show-toplevel']).toString().trim()) }
  catch { /* Pre-initialization projects acquire the exact ignore rules for their first commit. */ }
  if (gitRoot && gitRoot !== root) throw new ThreejsAssetPreparationError('Asset preparation requires the project Git root')
  const paths = entries.map(([rel]) => rel)
  if (gitRoot) {
    const staged = new Set(git(['diff', '--cached', '--name-only', '-z', ...(pkg.scripts.build.startsWith(restoreCommand + ' && ') ? ['--diff-filter=ACMRTUXB'] : [])]).toString().split('\0'))
    if (paths.some(rel => staged.has(rel))) throw new ThreejsAssetPreparationError('Unstage managed asset edits before synchronization; no index changes were made')
    const required = ['assets.lock.json', 'package.json', '.gitignore', ...files.map(([file]) => relative(root, file).split('\\').join('/'))]
    const tracked = new Set(git(['ls-files', '-z']).toString().split('\0'))
    for (const rel of required.filter(rel => !tracked.has(rel))) {
      try { git(['check-ignore', '--no-index', '--quiet', '--', rel]) }
      catch (error) { if (error.status === 1) continue; throw error }
      throw new ThreejsAssetPreparationError('Project ignore rules hide the asset manifest or recovery scripts; preserve these files in Git before synchronization')
    }
  }
  // Preserve the original command and all user checks. This also works in Webdev's remote builder.
  for (const script of ['build', 'dev']) {
    if (typeof pkg.scripts[script] === 'string' && !pkg.scripts[script].startsWith(restoreCommand + ' && ')) pkg.scripts[script] = restoreCommand + ' && ' + pkg.scripts[script]
  }
  for (const [file, content] of files) replaceFile(file, content)
  replaceFile(pkgPath, JSON.stringify(pkg, null, 2) + '\n')
  // Anchor and escape literal paths; never hide unrelated files with extension globs.
  const existingRules = new Set(ignore.split(/\r?\n/))
  const rules = paths.map(rel => '/' + rel.replace(/[\\*?\[\] !#]/g, '\\$&')).filter(rule => !existingRules.has(rule))
  if (rules.length) replaceFile(ignorePath, ignore + (ignore && !ignore.endsWith('\n') ? '\n' : '') + '# Assets restored from assets.lock.json\n' + rules.join('\n') + '\n')
  if (gitRoot && updateIndex) git(['rm', '--cached', '--ignore-unmatch', '--pathspec-from-file=-', '--pathspec-file-nul'], {
    input: paths.map(rel => ':(literal)' + rel + '\0').join(''),
  })
}
